#!/usr/bin/env node
// Inventory of the literal (untranslated) user-facing texts of the application, per file. It writes docs/guides/i18n-inventory.md and
// prints the totals. Development-only panels are excluded with `<!-- i18n-ignore:start --> ... <!-- i18n-ignore:end -->`.
// Run it with `pnpm run i18n:inventory`.
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {APP_DIR, ROOT, listFiles, literalTexts, rel, usedKeys} from './lib.mjs';

const SHOWCASE = /(components\/showcase\/|components\/ui\/.*(examples?|usage-example)|search-usage-example|button-usage-example|brand-showcase)/;

const templates = listFiles(APP_DIR, ['.html']).map((file) => ({file: rel(file), texts: literalTexts(readFileSync(file, 'utf8'))}));
const pendingTemplates = templates.filter((t) => t.texts.length > 0);

// Inline templates (`template: \`...\``) of user-facing components, and notification messages written in code.
const inline = [];
const notifications = [];
for (const file of listFiles(APP_DIR, ['.ts'])) {
  const source = readFileSync(file, 'utf8').replace(/^\s*\/\/.*$/gm, '');
  const path = rel(file);
  const match = source.match(/template:\s*`([\s\S]*?)`/);
  if (match && !SHOWCASE.test(path)) {
    const texts = literalTexts(match[1]);
    if (texts.length > 0) {
      inline.push({file: path, texts});
    }
  }
  const count = SHOWCASE.test(path) ? 0 : [...source.matchAll(/(?:notificationService|notification)\.(?:success|error|warning|info)\(\s*['"`]/g)].length;
  if (count > 0) {
    notifications.push({file: path, count});
  }
}

const total = (list) => list.reduce((sum, item) => sum + item.texts.length, 0);
const lines = [
  '# i18n inventory',
  '',
  'Generated by `pnpm run i18n:inventory` (do not edit by hand). It lists the literal texts that are **not** translated yet.',
  '',
  '| Group | Files | Literal texts |',
  '| --- | --- | --- |',
  `| Templates (\`.html\`) | ${pendingTemplates.length} | ${total(pendingTemplates)} |`,
  `| Inline templates of user-facing components | ${inline.length} | ${total(inline)} |`,
  `| Notification messages written in code | ${notifications.length} | ${notifications.reduce((s, n) => s + n.count, 0)} |`,
  '',
  `Excluded on purpose: developer showcase and usage examples (\`${SHOWCASE.source}\`) and the blocks marked \`i18n-ignore\` (development-only panels).`,
  ''
];
for (const [title, list] of [['Templates', pendingTemplates], ['Inline templates', inline]]) {
  lines.push(`## ${title}`, '');
  if (list.length === 0) {
    lines.push('Nothing pending.', '');
  }
  for (const item of list) {
    lines.push(`### \`${item.file}\``, '', ...item.texts.map((t) => `- \`${t.kind}\`: ${t.text}`), '');
  }
}
lines.push('## Notification messages in code', '');
lines.push(notifications.length === 0 ? 'Nothing pending.' : notifications.map((n) => `- \`${n.file}\`: ${n.count}`).join('\n'), '');

writeFileSync(join(ROOT, 'docs/guides/i18n-inventory.md'), lines.join('\n'));
console.log(`templates: ${pendingTemplates.length} files / ${total(pendingTemplates)} texts | inline templates: ${inline.length} files / ${total(inline)} texts | notifications: ${notifications.reduce((s, n) => s + n.count, 0)}`);
