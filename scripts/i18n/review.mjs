#!/usr/bin/env node
// Writes docs/guides/i18n-review.md: every text in es, en and fr side by side, grouped by section, with a checkbox per row for the human
// reviewers. Run it with `pnpm run i18n:review` after changing the translation files.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {LANGUAGES, ROOT, byText, loadLanguage} from './lib.mjs';

const languages = Object.fromEntries(LANGUAGES.map((language) => [language, loadLanguage(language)]));
const keys = Object.keys(languages.es).sort(byText);
const sections = new Map();
for (const key of keys) {
  const section = key.split('.')[0];
  sections.set(section, [...(sections.get(section) ?? []), key]);
}
const cell = (text) => String(text).replaceAll('|', String.raw`\|`).replaceAll('\n', ' ');

const lines = [
  '# Translation review (es / en / fr)',
  '',
  'Generated by `pnpm run i18n:review` (do not edit by hand). Spanish is the reference language. **The English and French texts were written by an AI assistant and have not been reviewed by a person yet**: reviewers tick the box of each row when the text is right, and correct it in `src/assets/i18n/<language>.json` when it is not.',
  '',
  `Keys: ${keys.length} in ${sections.size} sections.`,
  ''
];
for (const [section, sectionKeys] of sections) {
  lines.push(`## ${section} (${sectionKeys.length})`, '', '| Done | Key | es | en | fr |', '| --- | --- | --- | --- | --- |');
  for (const key of sectionKeys) {
    lines.push(`| [ ] | \`${key}\` | ${cell(languages.es[key])} | ${cell(languages.en[key])} | ${cell(languages.fr[key])} |`);
  }
  lines.push('');
}
writeFileSync(join(ROOT, 'docs/guides/i18n-review.md'), lines.join('\n'));
console.log(`review sheet written: ${keys.length} keys, ${sections.size} sections`);
